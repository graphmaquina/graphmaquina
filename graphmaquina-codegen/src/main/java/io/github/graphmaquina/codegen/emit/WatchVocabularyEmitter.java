package io.github.graphmaquina.codegen.emit;

import io.github.graphmaquina.codegen.model.GeneratedSource;
import io.github.graphmaquina.codegen.model.GraphDescriptor;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import java.util.Set;

/**
 * Emits the vocabulary of one ordered pair of machines: the top-level {@code <Owner><Peer>} declared in the
 * owner's package, holding {@code Watch}, its repeatable container and {@code When}, then {@code Submachine}, its
 * repeatable container and {@code Exit}.
 *
 * <p>The pair is fixed by the vocabulary itself, so no declaration repeats it. The owner's state enum types the
 * state being watched, the owner's transition enum types the edge each rule executes, and the peer's state enum
 * types the three filters, which makes a constant of the wrong machine a javac error rather than a diagnostic of
 * this tool. In the same way the owner's state enum types the state that holds a sub-machine, the peer's state
 * enum the terminal state of each exit, and the owner's transition enum the transition that exit selects. As in the
 * machine vocabulary, nothing is imported and every name this file does not declare itself is written qualified,
 * so the pair's name can never collide with an import, as {@code RetentionPolicy} would.</p>
 *
 * <p>Each name is still read through its first segment, and any type in scope here under that simple name takes the
 * name over: an annotation nested here shadows a type of that name (JLS 6.4.1) and obscures a package of that name,
 * and a type of the owner's package, a top-level type generated in that package, this file included, or a public
 * type of {@code java.lang} obscures the package it starts with (JLS 6.4.2). The bootstrap refuses a declaration
 * whose name a type of the package or of {@code java.lang} would take, and {@link #emit} one whose name a nested
 * annotation or a generated type would take, all with {@code SG603}.</p>
 */
final class WatchVocabularyEmitter {

    private static final List<String> ANNOTATIONS =
        List.of("Watch", "Watches", "When", "Submachine", "Submachines", "Exit");

    private WatchVocabularyEmitter() {
    }

    /** The canonical name of the vocabulary of the pair {@code owner} over {@code peer}, in the owner's package. */
    static String vocabularyName(GraphDescriptor owner, GraphDescriptor peer) {
        String simpleName = MachineVocabularyEmitter.hostName(owner) + MachineVocabularyEmitter.hostName(peer);
        return SymbolNames.qualified(owner.packageName(), simpleName);
    }

    /** The canonical names of the annotations the pair declares, in declaration order. */
    static List<String> annotationTypes(GraphDescriptor owner, GraphDescriptor peer) {
        String vocabulary = vocabularyName(owner, peer);
        return ANNOTATIONS.stream().map((String name) -> vocabulary + '.' + name).toList();
    }

    /**
     * The compilation unit carrying the vocabulary of the pair {@code owner} over {@code peer}.
     *
     * @param generated the simple names of the top-level types generated in each package
     * @throws io.github.graphmaquina.codegen.CodegenException {@code SG603} if a nested annotation of the
     *     vocabulary, or a top-level type generated in the owner's package, takes over the first segment of a
     *     machine or an enum it names
     */
    static GeneratedSource emit(GraphDescriptor owner, GraphDescriptor peer, Map<String, Set<String>> generated) {
        String vocabulary = vocabularyName(owner, peer);
        String simpleName = SymbolNames.nameWithin(owner.packageName(), vocabulary);
        String pair = "machine = " + owner.facade() + ".class, peer = " + peer.facade() + ".class";
        String unit = "the pair vocabulary " + simpleName;
        Map<String, String> named = new LinkedHashMap<>();
        named.put(owner.facade(), "the machine " + owner.facade());
        named.put(peer.facade(), "the peer machine " + peer.facade());
        named.put(owner.stateType(), "the state type " + owner.stateType() + " of " + owner.facade());
        named.put(owner.transitionType(), "the transition type " + owner.transitionType() + " of " + owner.facade());
        named.put(peer.stateType(), "the state type " + peer.stateType() + " of " + peer.facade());
        Map<String, String> meanings = ApiEmitter.meanings(simpleName, owner.packageName(), ANNOTATIONS, generated);
        for (Map.Entry<String, String> name : named.entrySet()) {
            ApiEmitter.requireNameable(unit, meanings, name.getValue(), name.getKey(), owner.origin());
        }

        JavaSource source = new JavaSource();
        source.header(owner.packageName(), List.of());
        source.javadoc("Typed vocabulary generated for the pair {@link " + owner.facade() + "} over {@link "
                + peer.facade() + "}: its watch and sub-machine annotations.",
            "",
            "<p>Generated by the StateGraph code generator. Do not edit.</p>");
        source.line("public final class " + simpleName + " {");
        source.indent();
        source.line("");
        source.line("private " + simpleName + "() {");
        source.line("}");

        watch(source, simpleName, pair, owner);
        watches(source, simpleName, pair, owner, peer);
        when(source, pair, owner, peer);
        submachine(source, simpleName, pair, owner, peer);
        submachines(source, simpleName, pair, owner, peer);
        exit(source, simpleName, pair, owner, peer);

        source.outdent();
        source.line("}");
        return new GeneratedSource(vocabulary, source.toString());
    }

    private static void watch(JavaSource source, String vocabulary, String pair, GraphDescriptor owner) {
        describe(source, "Watches the peers of {@link " + owner.facade() + "} while it is in one state and",
            "executes the transition of the first rule that holds.");
        annotation(source, pair, "WATCH", "java.lang.annotation.ElementType.TYPE", Optional.of(vocabulary + ".Watches"),
            "Watch");
        source.line(owner.stateType() + " state();");
        source.line(MachineVocabularyEmitter.symbolClass("PropertySymbol") + " peers();");
        source.line(MachineVocabularyEmitter.symbolClass("PropertySymbol") + " owner();");
        source.line(vocabulary + ".When[] rules();");
        close(source);
    }

    private static void watches(JavaSource source, String vocabulary, String pair,
            GraphDescriptor owner, GraphDescriptor peer) {
        describe(source, "Holds the repeated {@link " + vocabulary + ".Watch} declarations of {@link "
            + owner.facade() + "} over {@link " + peer.facade() + "}.");
        annotation(source, pair, "WATCHES", "java.lang.annotation.ElementType.TYPE", Optional.empty(), "Watches");
        source.line(vocabulary + ".Watch[] value();");
        close(source);
    }

    private static void when(JavaSource source, String pair, GraphDescriptor owner, GraphDescriptor peer) {
        describe(source, "One watch rule: the condition or the filter over the peers' states that must hold,",
            "and the transition of {@link " + owner.facade() + "} the entity executes.");
        annotation(source, pair, "WHEN", "{}", Optional.empty(), "When");
        source.line(MachineVocabularyEmitter.symbolClass("ConditionSymbol") + "[] condition() default {};");
        source.line(peer.stateType() + "[] allIn() default {};");
        source.line(peer.stateType() + "[] anyIn() default {};");
        source.line(peer.stateType() + "[] noneIn() default {};");
        source.line(owner.transitionType() + " transition();");
        close(source);
    }

    private static void submachine(JavaSource source, String vocabulary, String pair, GraphDescriptor owner,
            GraphDescriptor peer) {
        describe(source, "One sub-machine of {@link " + owner.facade() + "}: the state of {@link " + owner.facade()
                + "} that holds a {@link " + peer.facade() + "},",
            "how to reach the child from the parent and back, and the transition of {@link " + owner.facade() + "}",
            "each terminal state of the child selects.");
        annotation(source, pair, "SUBMACHINE", "java.lang.annotation.ElementType.TYPE",
            Optional.of(vocabulary + ".Submachines"), "Submachine");
        source.line(owner.stateType() + " state();");
        source.line(MachineVocabularyEmitter.symbolClass("PropertySymbol") + "[] child() default {};");
        source.line(MachineVocabularyEmitter.symbolClass("PropertySymbol") + "[] parent() default {};");
        source.line(MachineVocabularyEmitter.symbolClass("LookupSymbol") + "[] parentLookup() default {};");
        source.line(vocabulary + ".Exit[] exits();");
        close(source);
    }

    private static void submachines(JavaSource source, String vocabulary, String pair,
            GraphDescriptor owner, GraphDescriptor peer) {
        describe(source, "Holds the repeated {@link " + vocabulary + ".Submachine} declarations of {@link "
            + owner.facade() + "} over {@link " + peer.facade() + "}.");
        annotation(source, pair, "SUBMACHINES", "java.lang.annotation.ElementType.TYPE", Optional.empty(),
            "Submachines");
        source.line(vocabulary + ".Submachine[] value();");
        close(source);
    }

    private static void exit(JavaSource source, String vocabulary, String pair, GraphDescriptor owner,
            GraphDescriptor peer) {
        describe(source, "One exit in the {@code exits} of a {@link " + vocabulary + ".Submachine}: a terminal state"
                + " of {@link " + peer.facade() + "}",
            "and the transition of {@link " + owner.facade() + "} it selects.");
        annotation(source, pair, "EXIT", "{}", Optional.empty(), "Exit");
        source.line(peer.stateType() + " on();");
        source.line(owner.transitionType() + " transition();");
        close(source);
    }

    /** Writes the blank line and the documentation comment preceding one nested annotation. */
    private static void describe(JavaSource source, String... javadoc) {
        source.line("");
        source.javadoc(javadoc);
    }

    /** Writes the metadata, target, retention and repeatability of one nested annotation and opens its body. */
    private static void annotation(JavaSource source, String pair, String kind, String target,
            Optional<String> container, String name) {
        source.line("@io.github.graphmaquina.annotation.internal.GeneratedVocabulary(" + pair
            + ", value = io.github.graphmaquina.annotation.internal.VocabularyKind." + kind + ")");
        source.line("@java.lang.annotation.Target(" + target + ")");
        source.line("@java.lang.annotation.Retention(java.lang.annotation.RetentionPolicy.CLASS)");
        container.ifPresent((String repeated) ->
            source.line("@java.lang.annotation.Repeatable(" + repeated + ".class)"));
        source.line("public @interface " + name + " {");
        source.indent();
    }

    private static void close(JavaSource source) {
        source.outdent();
        source.line("}");
    }
}
