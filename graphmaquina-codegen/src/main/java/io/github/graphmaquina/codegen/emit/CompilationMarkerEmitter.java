package io.github.graphmaquina.codegen.emit;

import io.github.graphmaquina.annotation.internal.GraphCompilation;
import io.github.graphmaquina.codegen.GenerationFiles;
import io.github.graphmaquina.codegen.model.GeneratedSource;
import java.nio.charset.StandardCharsets;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.List;
import java.util.Locale;

/**
 * Emits the carrier of one compilation: a tool-internal type in {@code io.github.graphmaquina.generated.bootstrap} that
 * only holds {@code @GraphCompilation}.
 *
 * <p>The carrier is emitted for every run, including one whose model is empty, so the annotation processor always
 * sees the compilation it belongs to and can publish an empty index when the last machine or member is deleted.
 * Its name ends with the first sixteen hexadecimal digits of the SHA-256 of the compilation identifier, so two
 * compilations claim the same carrier exactly when they are given the same identifier, as the Maven plugin gives its
 * main and its test compilation once {@code graphmaquina.compilationId} is set, or when two different identifiers
 * have digests whose first 64 bits are equal. Neither this generator nor the annotation processor compares
 * identifiers. While the other compilation's carrier class is still on the classpath, outside this compilation's
 * own class output, the generation refuses its own carrier with {@code SG603} as a type that would shadow that
 * class; once the other compilation's {@code complete-compile} has deleted it, both compilations go through, and
 * the other's export index, read from the classpath as a dependency, carries this compilation's own identifier.</p>
 *
 * <p>The documentation it carries says where it can be seen: {@code complete-compile} removes its class file from
 * the class output, so the binary jar never contains it; the Gradle plugin also keeps its source out of the
 * {@code sourcesJar} and {@code javadoc} of the source set; under Maven, a sources or javadoc plugin may still
 * pick up its {@code .java} from the generated source root.</p>
 */
final class CompilationMarkerEmitter {

    private static final int NAME_LENGTH = 16;

    private CompilationMarkerEmitter() {
    }

    /** The canonical name of the carrier of {@code compilationId}. */
    static String carrierName(String compilationId) {
        return GenerationFiles.CARRIER_PACKAGE + ".GraphCompilation" + digest(compilationId);
    }

    /** The compilation unit carrying {@code compilationId}. */
    static GeneratedSource emit(String compilationId) {
        String carrier = carrierName(compilationId);
        String simpleName = carrier.substring(carrier.lastIndexOf('.') + 1);

        JavaSource source = new JavaSource();
        source.header(GenerationFiles.CARRIER_PACKAGE, List.of(GraphCompilation.class.getName()));
        source.javadoc("Carries the identity of one compilation for the StateGraph annotation processor.",
            "",
            "<p>Tool-internal: this type is not API and must not be referenced by an application. The completion of",
            "the compilation removes its class file from the class output, so a binary jar never contains it. The",
            "StateGraph Gradle plugin also keeps this source out of the sources jar and the API documentation of its",
            "source set; under Maven, a sources or javadoc plugin may still pick it up from the generated source",
            "root. Generated by the StateGraph code generator. Do not edit.</p>");
        source.line("@GraphCompilation(\"" + escaped(compilationId) + "\")");
        source.line("public final class " + simpleName + " {");
        source.indent();
        source.line("");
        source.line("private " + simpleName + "() {");
        source.line("}");
        source.outdent();
        source.line("}");
        return new GeneratedSource(carrier, source.toString());
    }

    /** The first sixteen hexadecimal digits of the SHA-256 of {@code compilationId}, in its UTF-8 encoding. */
    private static String digest(String compilationId) {
        try {
            byte[] hash = MessageDigest.getInstance("SHA-256")
                    .digest(compilationId.getBytes(StandardCharsets.UTF_8));
            return HexFormat.of().formatHex(hash).substring(0, NAME_LENGTH);
        } catch (NoSuchAlgorithmException failure) {
            throw new IllegalStateException(
                "this Java runtime does not provide SHA-256, which names the compilation carrier", failure);
        }
    }

    /**
     * {@code compilationId} as the body of a Java string literal, so any quoting it carries survives: a quote and a
     * backslash are escaped, and every control character, U+0000 to U+001F, U+007F and U+0080 to U+009F, becomes
     * an octal escape, since a line break would end the literal and none of them belongs in source text.
     */
    private static String escaped(String compilationId) {
        StringBuilder literal = new StringBuilder(compilationId.length());
        for (int index = 0; index < compilationId.length(); index++) {
            char character = compilationId.charAt(index);
            if (character == '\\' || character == '"') {
                literal.append('\\').append(character);
            } else if (Character.isISOControl(character)) {
                literal.append(String.format(Locale.ROOT, "\\%03o", (int) character));
            } else {
                literal.append(character);
            }
        }
        return literal.toString();
    }
}
