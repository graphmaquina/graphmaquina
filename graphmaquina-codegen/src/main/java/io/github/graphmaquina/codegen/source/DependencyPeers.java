package io.github.graphmaquina.codegen.source;

import io.github.graphmaquina.annotation.internal.DiagnosticCode;
import io.github.graphmaquina.codegen.CodegenException;
import io.github.graphmaquina.codegen.emit.ApiEmitter;
import io.github.graphmaquina.codegen.manifest.PublishedIndex;
import io.github.graphmaquina.codegen.model.GraphDescriptor;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Optional;
import lombok.AccessLevel;
import lombok.RequiredArgsConstructor;

/**
 * Resolves the declared peers that this compilation does not generate against the export indexes of its dependencies.
 *
 * <p>A peer is first one of the machines of this compilation, which {@link MachineHeaders#requireWatchablePeers}
 * has already checked. Any other peer read from the classpath is the machine the export index of a dependency
 * describes by its canonical name, the name a manifest knows a machine by; the pair vocabulary is then typed from that
 * descriptor. A peer that is a type of the sources and no machine of this compilation is no machine of a dependency
 * either, whatever an index describes under its name. No two indexes describe one machine, which
 * {@link io.github.graphmaquina.codegen.manifest.DependencyExports#read} has already refused, and a machine of this
 * compilation that an index describes too is refused by {@link #refuseDescribedMachines}, which runs before any
 * machine, and so any peer, is resolved.</p>
 */
@RequiredArgsConstructor(access = AccessLevel.PRIVATE)
final class DependencyPeers {

    /**
     * Refuses a machine of this compilation that an index of {@code dependencies} describes too, whether or not it is
     * anyone's peer. Only the facades are read, so this runs before any machine, and so any peer, is resolved.
     *
     * @param facades the facades of the machines this compilation generates, each an original source declaration
     * @param dependencies the export indexes the dependencies publish, each with its classpath entry
     * @throws CodegenException {@code SG602} anchored at the first such facade, naming the entry of the first index
     *     that describes it
     */
    static void refuseDescribedMachines(List<TypeHeader> facades, List<PublishedIndex> dependencies) {
        for (TypeHeader facade : facades) {
            Optional<PublishedIndex> describing = describing(dependencies, facade.canonicalName());
            if (describing.isPresent()) {
                throw new CodegenException(DiagnosticCode.SG602.name(), "the machine " + facade.canonicalName()
                        + " is generated by this compilation and also described by the export index of "
                        + describing.get().entry(), facade.origin().orElseThrow());
            }
        }
    }

    /**
     * The descriptors of the peers of {@code machines} that none of them is, as the one index of
     * {@code dependencies} that describes each gives it: every one once, in the order the machines, and then the
     * peers each machine declares, first name it. Only a peer read from the classpath takes a descriptor: a type of
     * the sources is no machine of a dependency.
     *
     * @param index the declarations the machines were resolved in
     * @param machines the machines this compilation generates, as resolved
     * @param dependencies the export indexes the dependencies publish, each with its classpath entry
     * @return the descriptors of the dependency peers, without repetition
     * @throws CodegenException {@code SG608} anchored at the owner of a peer that is neither a machine of this
     *     compilation nor a classpath type an index describes
     */
    static List<GraphDescriptor> resolve(DeclarationIndex index, List<MachineHeaders.Resolved> machines,
            List<PublishedIndex> dependencies) {
        Map<String, GraphDescriptor> peers = new LinkedHashMap<>();
        for (MachineHeaders.Resolved owner : machines) {
            for (TypeHeader peer : owner.peers()) {
                if (machines.stream().noneMatch((MachineHeaders.Resolved machine) -> machine.facade() == peer)) {
                    String name = peer.canonicalName();
                    Optional<GraphDescriptor> descriptor = peer.origin().isEmpty()
                            ? descriptor(dependencies, name)
                            : Optional.empty();
                    peers.putIfAbsent(name,
                            descriptor.orElseThrow(() -> ApiEmitter.unknownPeer(name, owner.graph())));
                }
            }
        }
        return List.copyOf(peers.values());
    }

    /** The first index of {@code dependencies} that describes the machine {@code facade}. */
    private static Optional<PublishedIndex> describing(List<PublishedIndex> dependencies, String facade) {
        return dependencies.stream()
                .filter((PublishedIndex published) -> descriptor(published, facade).isPresent())
                .findFirst();
    }

    /** The descriptor of the machine {@code facade} that the first index of {@code dependencies} to describe it gives. */
    private static Optional<GraphDescriptor> descriptor(List<PublishedIndex> dependencies, String facade) {
        return dependencies.stream()
                .flatMap((PublishedIndex published) -> descriptor(published, facade).stream())
                .findFirst();
    }

    /** The descriptor of the machine {@code facade} in {@code published}, the first if it lists that machine twice. */
    private static Optional<GraphDescriptor> descriptor(PublishedIndex published, String facade) {
        return published.index().model().graphs().stream()
                .filter((GraphDescriptor graph) -> graph.facade().equals(facade))
                .findFirst();
    }
}
