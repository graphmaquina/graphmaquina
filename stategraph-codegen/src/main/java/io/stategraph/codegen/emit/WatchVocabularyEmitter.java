package io.stategraph.codegen.emit;

import io.stategraph.codegen.model.GeneratedSource;
import io.stategraph.codegen.model.GraphDescriptor;
import java.util.List;

/**
 * Emits the watch vocabulary of one ordered pair of machines: the top-level {@code <Owner><Peer>} declared in the
 * owner's package, holding {@code Watch}, its repeatable container and {@code When}.
 *
 * <p>The pair is fixed by the vocabulary itself, so no declaration repeats it. The owner's enum types the state
 * being watched and every destination, and the peer's enum types the three filters, which makes a constant of the
 * wrong machine a javac error rather than a diagnostic of this tool.</p>
 */
final class WatchVocabularyEmitter {

    private static final List<String> IMPORTS = List.of(
        "io.stategraph.annotation.internal.GeneratedVocabulary",
        "io.stategraph.annotation.internal.VocabularyKind",
        "io.stategraph.symbol.ConditionSymbol",
        "io.stategraph.symbol.PropertySymbol",
        "java.lang.annotation.ElementType",
        "java.lang.annotation.Repeatable",
        "java.lang.annotation.Retention",
        "java.lang.annotation.RetentionPolicy",
        "java.lang.annotation.Target");

    private WatchVocabularyEmitter() {
    }

    /** The canonical name of the watch vocabulary generated for {@code owner} watching {@code peer}. */
    static String vocabularyName(String owner, String peer) {
        String packageName = SymbolNames.packageOf(owner);
        String simpleName = SymbolNames.hostName(SymbolNames.nameWithoutPackage(owner))
            + SymbolNames.hostName(SymbolNames.nameWithoutPackage(peer));
        return packageName.isEmpty() ? simpleName : packageName + '.' + simpleName;
    }

    /** The canonical names of the annotations the pair declares, in declaration order. */
    static List<String> annotationTypes(GraphDescriptor owner, GraphDescriptor peer) {
        String vocabulary = vocabularyName(owner.facade(), peer.facade());
        return List.of(vocabulary + ".Watch", vocabulary + ".Watches", vocabulary + ".When");
    }

    /** The compilation unit carrying the watch vocabulary of {@code owner} over {@code peer}. */
    static GeneratedSource emit(GraphDescriptor owner, GraphDescriptor peer) {
        String vocabulary = vocabularyName(owner.facade(), peer.facade());
        String simpleName = vocabulary.substring(vocabulary.lastIndexOf('.') + 1);
        String pair = "machine = " + owner.facade() + ".class, peer = " + peer.facade() + ".class";

        JavaSource source = new JavaSource();
        source.header(SymbolNames.packageOf(vocabulary), IMPORTS);
        source.javadoc("Typed watch vocabulary generated for {@link " + owner.facade() + "} over {@link "
                + peer.facade() + "}.",
            "",
            "<p>Generated by the StateGraph code generator. Do not edit.</p>");
        source.line("public final class " + simpleName + " {");
        source.indent();
        source.line("");
        source.line("private " + simpleName + "() {");
        source.line("}");

        watch(source, simpleName, pair, owner);
        watches(source, simpleName, pair, owner, peer);
        when(source, pair, owner, peer);

        source.outdent();
        source.line("}");
        return new GeneratedSource(vocabulary, source.toString());
    }

    private static void watch(JavaSource source, String vocabulary, String pair, GraphDescriptor owner) {
        describe(source, "Watches the peers of {@link " + owner.facade() + "} while it is in one state and",
            "moves it with the first rule that holds.");
        annotation(source, pair, "WATCH", "ElementType.TYPE", vocabulary + ".Watches", "Watch");
        source.line(owner.stateType() + " state();");
        source.line("Class<? extends PropertySymbol> peers();");
        source.line("Class<? extends PropertySymbol> owner();");
        source.line(vocabulary + ".When[] rules();");
        close(source);
    }

    private static void watches(JavaSource source, String vocabulary, String pair,
            GraphDescriptor owner, GraphDescriptor peer) {
        describe(source, "Holds the repeated {@link " + vocabulary + ".Watch} declarations of {@link "
            + owner.facade() + "} over {@link " + peer.facade() + "}.");
        annotation(source, pair, "WATCHES", "ElementType.TYPE", null, "Watches");
        source.line(vocabulary + ".Watch[] value();");
        close(source);
    }

    private static void when(JavaSource source, String pair, GraphDescriptor owner, GraphDescriptor peer) {
        describe(source, "One watch rule: the condition or the filter over the peers' states that must hold,",
            "and the state of {@link " + owner.facade() + "} the entity moves to.");
        annotation(source, pair, "WHEN", "{}", null, "When");
        source.line("Class<? extends ConditionSymbol>[] condition() default {};");
        source.line(peer.stateType() + "[] allIn() default {};");
        source.line(peer.stateType() + "[] anyIn() default {};");
        source.line(peer.stateType() + "[] noneIn() default {};");
        source.line(owner.stateType() + " goTo();");
        close(source);
    }

    /** Writes the blank line and the documentation comment preceding one nested annotation. */
    private static void describe(JavaSource source, String... javadoc) {
        source.line("");
        source.javadoc(javadoc);
    }

    /** Writes the metadata, target, retention and repeatability of one nested annotation and opens its body. */
    private static void annotation(JavaSource source, String pair, String kind, String target,
            String container, String name) {
        source.line("@GeneratedVocabulary(" + pair + ", value = VocabularyKind." + kind + ")");
        source.line("@Target(" + target + ")");
        source.line("@Retention(RetentionPolicy.CLASS)");
        if (container != null) {
            source.line("@Repeatable(" + container + ".class)");
        }
        source.line("public @interface " + name + " {");
        source.indent();
    }

    private static void close(JavaSource source) {
        source.outdent();
        source.line("}");
    }
}
